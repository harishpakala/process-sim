#!/usr/bin/env python3
"""Import Assets, Products, DEXPI and ECAD RDF into GraphDB.

Assets and Products are generated by scripts/export_asset_kg.py from the
example AAS JSON. DEXPI and ECAD require existing RDF files; this script
does not invent or convert engineering source data.

Examples:
  python3 scripts/import_knowledge_graph.py --assets-products
  python3 scripts/import_knowledge_graph.py --all --dexpi path/to/dexpi.ttl --ecad path/to/ecad.ttl
  python3 scripts/import_knowledge_graph.py --all --dexpi path/to/dexpi.rdf --ecad path/to/ecad.ttl --endpoint http://localhost:7200/repositories/AAS

Imports append triples to the repository default graph. Existing triples
are not removed; repeated uploads do not implement synchronization.
"""
import argparse
import os
from pathlib import Path
import subprocess
import sys
import urllib.error
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / "examples/kg/tep_asset_product_graph.ttl"
MEDIA_TYPES = {
    ".ttl": "text/turtle",
    ".nt": "application/n-triples",
    ".rdf": "application/rdf+xml",
    ".owl": "application/rdf+xml",
    ".nq": "application/n-quads",
    ".trig": "application/trig",
}


def upload(path: Path, endpoint: str) -> None:
    if not path.is_file():
        raise FileNotFoundError(f"RDF input not found: {path}")
    content_type = MEDIA_TYPES.get(path.suffix.lower())
    if not content_type:
        raise ValueError(f"Unsupported RDF format for {path}; supported: {', '.join(MEDIA_TYPES)}")
    data = path.read_bytes()
    if not data.strip():
        raise ValueError(f"RDF input is empty: {path}")
    url = endpoint.rstrip("/") + "/statements"
    request = urllib.request.Request(
        url, data=data, method="POST",
        headers={"Content-Type": content_type + "; charset=utf-8"},
    )
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            print(f"Uploaded {path} -> {url} (HTTP {response.status})")
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")[:500]
        raise RuntimeError(f"Upload failed for {path}: HTTP {exc.code}: {detail}") from exc
    except urllib.error.URLError as exc:
        raise RuntimeError(f"Cannot reach GraphDB at {url}: {exc.reason}") from exc


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--all", action="store_true", help="Require and upload all four datasets")
    mode.add_argument("--assets-products", action="store_true", help="Generate and upload Assets and Products only")
    parser.add_argument("--dexpi", type=Path, help="Path to an existing DEXPI RDF file")
    parser.add_argument("--ecad", type=Path, help="Path to an existing ECAD RDF file")
    parser.add_argument("--endpoint", default=os.environ.get("GRAPHDB_SPARQL_ENDPOINT", "http://localhost:7200/repositories/AAS"), help="GraphDB SPARQL repository endpoint")
    args = parser.parse_args()

    if args.all and (args.dexpi is None or args.ecad is None):
        parser.error("--all requires both --dexpi and --ecad RDF file paths")
    if args.assets_products and (args.dexpi is not None or args.ecad is not None):
        parser.error("Use --all when providing DEXPI and ECAD files")

    sources = [(label, path.resolve()) for label, path in
               (("DEXPI", args.dexpi), ("ECAD", args.ecad)) if path is not None]
    # Validate external inputs before modifying GraphDB.
    for label, path in sources:
        if not path.is_file():
            parser.error(f"{label} RDF file not found: {path}")
        if path.suffix.lower() not in MEDIA_TYPES:
            parser.error(f"{label} file is not a supported RDF format: {path}")
        if not path.read_bytes().strip():
            parser.error(f"{label} RDF file is empty: {path}")

    subprocess.run([sys.executable, str(ROOT / "scripts/export_asset_kg.py")], check=True)
    upload(GENERATED, args.endpoint)
    for label, path in sources:
        print(f"Importing {label}...")
        upload(path, args.endpoint)
    print("Import completed. Verify resource counts in GraphDB Workbench.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
