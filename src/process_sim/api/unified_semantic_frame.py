"""Experimental one-pass semantic frame extraction, shared across query types.

A single model response proposes intent, schema domain/entity, identifiers and
simulation time. Every proposed identifier must occur verbatim in the question
or explicit context; entity/domain choices must exist in the SHACL catalog.
This is planning only; no SQL or SPARQL is generated by the model.
"""
from __future__ import annotations

from dataclasses import dataclass
import re
from uuid import UUID

from process_sim.api.unified_intent_selector import _model_choice, _schema_catalog
from process_sim.api.unified_query_plan import TemporalWindow

_FIELDS = {"intent", "domain", "entity", "local_id", "run_id",
           "start_seconds", "end_seconds"}
_INTENTS = {"graph_query", "observations", "mixed", "unsupported"}
_CONTEXT = {"domain", "engineering_function", "run_id",
            "start_simulation_seconds", "end_simulation_seconds"}


@dataclass(frozen=True)
class SemanticFrame:
    intent: str
    domain: str | None
    entity: str | None
    local_id: str | None
    run_id: str | None
    temporal: TemporalWindow


def _merge(field, proposed, selected):
    if proposed is not None and selected is not None and proposed != selected:
        raise ValueError(f"Question and selected context disagree on {field}")
    return proposed if proposed is not None else selected


def interpret_semantic_frame(question, schema, *, context=None, interpret=None):
    """Validate one semantic model frame against question, context and SHACL."""
    if not isinstance(question, str) or not 5 <= len(question.strip()) <= 1000:
        raise ValueError("Question must contain 5–1000 characters")
    context = {} if context is None else context
    if not isinstance(context, dict) or set(context) - _CONTEXT:
        raise ValueError("Invalid semantic context")
    catalog = _schema_catalog(schema)
    if not catalog:
        raise ValueError("No SHACL-validated entities available")
    if interpret is None:
        import json
        import os
        from urllib.request import Request, urlopen
        system = (
            "Return ONLY JSON with EXACTLY these keys: intent, domain, entity, "
            "local_id, run_id, start_seconds, end_seconds. "
            "Intent is graph_query, observations, mixed or unsupported. "
            "Select domain and entity ONLY from the supplied SHACL catalog. "
            "Copy local_id and run_id verbatim from the question; never invent them. "
            "Simulation times are numbers in seconds or null. "
            "Use null for unknown values. If both graph relations and historical "
            "observations are requested, choose mixed. Do not generate SPARQL or SQL."
        )
        request = Request(
            os.environ.get("OLLAMA_HOST", "http://localhost:11434").rstrip("/") + "/api/chat",
            data=json.dumps({
                "model": os.environ.get("DTWISE_QWEN_MODEL", "qwen2.5-coder:3b"),
                "stream": False, "format": "json",
                "messages": [{"role": "system", "content": system},
                             {"role": "user", "content": json.dumps({
                                 "question": question, "shacl_entities": catalog})}],
            }).encode(), headers={"Content-Type": "application/json"}, method="POST")
        with urlopen(request, timeout=60) as response:
            proposed = json.loads(json.load(response)["message"]["content"])
    else:
        proposed = interpret(question, catalog)
    if not isinstance(proposed, dict) or set(proposed) != _FIELDS:
        raise ValueError("Semantic frame has missing or unexpected fields")
    intent = proposed["intent"]
    if intent not in _INTENTS or intent == "unsupported":
        raise ValueError("Unsupported semantic frame intent")
    domain = proposed["domain"]
    entity = proposed["entity"]
    if domain is not None and not isinstance(domain, str):
        raise ValueError("Invalid domain")
    if entity is not None and not isinstance(entity, str):
        raise ValueError("Invalid entity")
    selected_domain = context.get("domain")
    if selected_domain is not None and not isinstance(selected_domain, str):
        raise ValueError("Invalid selected domain")
    domain = _merge("domain", domain, selected_domain)
    if domain is not None and domain not in {x["domain"] for x in catalog}:
        raise ValueError("Domain lacks SHACL grounding")
    if entity is not None and (domain, entity) not in {
        (x["domain"], x["entity"]) for x in catalog}:
        raise ValueError("Entity lacks SHACL grounding")
    # A model cannot introduce a new identifier. Explicit UI context is trusted
    # only as user selection and cannot contradict identifiers in the question.
    local_id = proposed["local_id"]
    selected_id = context.get("engineering_function")
    for value in (local_id, selected_id):
        if value is not None and (not isinstance(value, str) or
                                  not re.fullmatch(r"[A-Za-z][A-Za-z0-9_-]{1,79}", value)):
            raise ValueError("Invalid engineering identifier")
    if local_id is not None and not re.search(
        r"(?<![A-Za-z0-9_-])" + re.escape(local_id) + r"(?![A-Za-z0-9_-])",
        question, re.I
    ):
        raise ValueError("Model invented an engineering identifier")
    mentioned_ids = set(re.findall(r"(?<![A-Za-z0-9_-])(?:FI|LI|PI|TI)[_-][0-9]+(?![A-Za-z0-9_-])", question, re.I))
    if len({v.upper() for v in mentioned_ids}) > 1:
        raise ValueError("Multiple engineering identifiers need disambiguation")
    if mentioned_ids and local_id is None:
        raise ValueError("Semantic frame omitted an explicit engineering identifier")
    local_id = _merge("local_id", local_id.upper() if local_id else None,
                      selected_id.upper() if selected_id else None)
    if mentioned_ids and local_id != next(iter(mentioned_ids)).upper():
        raise ValueError("Semantic frame contradicts question identifier")
    run_id = proposed["run_id"]
    selected_run = context.get("run_id")
    try:
        run_id = str(UUID(run_id)) if run_id is not None else None
        selected_run = str(UUID(selected_run)) if selected_run is not None else None
    except (ValueError, TypeError, AttributeError) as exc:
        raise ValueError("Invalid simulation run UUID") from exc
    uuids = {str(UUID(x)) for x in re.findall(
        r"(?<![a-fA-F0-9])[a-fA-F0-9]{8}(?:-[a-fA-F0-9]{4}){3}-[a-fA-F0-9]{12}(?![a-fA-F0-9])",
        question)}
    if len(uuids) > 1 or (run_id and run_id not in uuids):
        raise ValueError("Model invented or ambiguously selected simulation run")
    if uuids and run_id is None:
        raise ValueError("Semantic frame omitted explicit simulation run")
    run_id = _merge("run_id", run_id, selected_run)
    if uuids and run_id != next(iter(uuids)):
        raise ValueError("Semantic frame contradicts question run")
    start = _merge("start_seconds", proposed["start_seconds"],
                   context.get("start_simulation_seconds"))
    end = _merge("end_seconds", proposed["end_seconds"],
                 context.get("end_simulation_seconds"))
    for key, proposed_time in (("start_simulation_seconds", proposed["start_seconds"]),
                               ("end_simulation_seconds", proposed["end_seconds"])):
        if proposed_time is not None:
            if isinstance(proposed_time, bool) or not isinstance(proposed_time, (int, float)):
                raise ValueError("Model proposed an invalid simulation time")
            if not any(float(token) == proposed_time for token in re.findall(
                r"(?<![A-Za-z0-9_.])\\d+(?:\\.\\d+)?(?![A-Za-z0-9_.])",
                re.sub(r"[0-9a-fA-F]{8}(?:-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}", "", question))):
                raise ValueError("Model invented a simulation time")
    temporal = TemporalWindow(start, end)
    if intent in ("observations", "mixed") and (not domain or not local_id or not run_id):
        raise ValueError("Observations require domain, LocalID and run UUID")
    return SemanticFrame(intent, domain, entity, local_id, run_id, temporal)
