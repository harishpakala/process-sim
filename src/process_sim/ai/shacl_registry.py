"""Extract authoritative SHACL paths from the existing AAS template lifting.

This module reuses semantic.template_lifting.build_template_graph, rather than
implementing a second AAS->RDF translator. No GraphDB connection is required.
"""
from __future__ import annotations

import json
from pathlib import Path

from rdflib import RDF, RDFS, URIRef
from rdflib.namespace import SH, OWL
import aas_core3_1.jsonization as aas_jsonization

from semantic.config import TARGETS
from semantic.template_lifting import build_template_graph
from .semantic_registry import build_registry


def _text(graph, node, predicate):
    value = graph.value(node, predicate)
    return str(value) if value is not None else None


def _walk_shape(graph, node, *, visited=None, parent=None):
    """Walk sh:property and sh:node edges, preserving parent-path context."""
    visited = set() if visited is None else visited
    if node in visited:
        return []
    visited.add(node)
    records = []
    for prop in graph.objects(node, SH.property):
        predicate = graph.value(prop, SH.path)
        if not isinstance(predicate, URIRef):
            # Complex SHACL property paths require separate planner handling.
            continue
        record = {
            "predicate": str(predicate),
            "parentPredicate": parent,
            "datatype": _text(graph, prop, SH.datatype),
            "valueClass": _text(graph, prop, SH["class"]),
            "minCount": _text(graph, prop, SH.minCount),
            "maxCount": _text(graph, prop, SH.maxCount),
            "nodeShape": _text(graph, prop, SH.node),
        }
        records.append(record)
        child = graph.value(prop, SH.node)
        if child is not None:
            records.extend(_walk_shape(graph, child, visited=visited,
                                       parent=str(predicate)))
    return records


def build_shacl_registry(*, targets=None):
    """Compile SHACL from configured templates and join instance-derived semantics.

    Output is a planning catalog, not a claim that a specific GraphDB graph is loaded.
    """
    targets = TARGETS if targets is None else targets
    instance_catalog = build_registry(targets=targets)
    domains = []
    for (domain, template_path, instance_path), declared in zip(targets, instance_catalog["domains"]):
        raw = json.loads(Path(template_path).read_text(encoding="utf-8"))
        template = aas_jsonization.submodel_from_jsonable(raw)
        graph = build_template_graph(template, domain)
        shapes = []
        for shape in graph.subjects(RDF.type, SH.NodeShape):
            target = graph.value(shape, SH.targetClass)
            if target is not None:
                shapes.extend(_walk_shape(graph, shape))
        declared_predicates = {p["iri"]: p for p in declared["predicates"]}
        for shape in shapes:
            # SHACL paths are produced by the authoritative template lifting.
            if shape["predicate"] not in declared_predicates:
                raise ValueError(f"SHACL path absent from lifting catalog: {shape['predicate']}")
        domains.append({
            "domain": domain,
            "templateId": template.id,
            "templateGraph": str(template_path),
            "instanceSource": str(instance_path),
            "templateClasses": sorted(str(s) for s in graph.subjects(RDF.type, OWL.Class)),
            "instanceClasses": declared["classes"],
            "predicates": declared["predicates"],
            "shaclPaths": shapes,
            "shapeCount": len(set(graph.subjects(RDF.type, SH.NodeShape))),
            "tripleCount": len(graph),
        })
    return {"domains": domains,
            "note": "SHACL generated by existing template lifting; instance semantics derived from existing instance lifting conventions. No GraphDB ingestion is asserted."}


def planner_shacl_context(registry, *, domains=None, max_paths=200):
    """Produce bounded, optionally domain-scoped context; never silently truncate."""
    selected = [d for d in registry["domains"]
                if domains is None or d["domain"] in domains]
    if domains is not None and {d["domain"] for d in selected} != set(domains):
        raise ValueError("Unknown requested semantic domain")
    count = sum(len(d["shaclPaths"]) for d in selected)
    if count > max_paths:
        raise ValueError("SHACL registry exceeds planner budget; select fewer domains")
    return {"domains": [{
        "domain": d["domain"],
        "shaclPaths": d["shaclPaths"],
        "instanceClasses": d["instanceClasses"],
        "instancePredicates": [p for p in d["predicates"] if "instance" in p["sources"]],
    } for d in selected], "note": registry["note"]}
