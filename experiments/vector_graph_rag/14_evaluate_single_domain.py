"""Evaluate single-domain property selection and constrained SPARQL planning.

Reads an existing retrieval report; no Ollama, SPARQL execution, or gold-driven
selection. Gold concepts are used for scoring only. Provisional labels require review.
"""
import argparse
import importlib.util
import json
from pathlib import Path

ROOT = Path("experiments/vector_graph_rag")
DEFAULT_RETRIEVAL = ROOT / "data/hybrid_evaluation_33_v3.json"
DEFAULT_INDEX = Path("semantic/ontology/dtwise/dtwise-schema-index.json")
DEFAULT_OUTPUT = ROOT / "data/single_domain_evaluation.json"


def load_planner():
    path = Path(__file__).with_name("08_constrained_query_planner.py")
    spec = importlib.util.spec_from_file_location("dtwise_single_domain_planner", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def evaluate(index, report, planner, max_cases=15):
    rows = []
    skipped = []
    for row in report.get("results", []):
        question = row.get("question", "")
        gold = row.get("gold_concepts", [])
        domains = set(row.get("expected_domains", [])) or {g.get("domain") for g in gold}
        if len(domains) != 1:
            skipped.append({"question": question, "reason": "Not a single-domain question"})
            continue
        domain = next(iter(domains))
        properties = {(g.get("domain"), g.get("uri")) for g in gold
                      if g.get("domain") == domain and isinstance(g.get("uri"), str)}
        if len(properties) != 1:
            skipped.append({"question": question, "reason": "Requires exactly one gold property for this v1 planner"})
            continue
        expected = next(iter(properties))
        indexed = {(c.get("domain"), c.get("uri")) for c in index.get("concepts", [])
                   if c.get("kind") == "property"}
        if expected not in indexed:
            skipped.append({"question": question, "reason": "Gold concept is not an indexed property"})
            continue
        hits = row.get("hybrid", {}).get("hits", [])
        # Domain scope is supplied as an oracle here, not autonomously predicted.
        domain_hits = [h for h in hits if h.get("domain") == domain
                       and (h.get("domain"), h.get("uri")) in indexed]
        selected = domain_hits[0] if domain_hits else None
        plan = planner.plan(index, question,
                            [{"domain": domain, "uri": selected["uri"]}] if selected else [],
                            hits, requested_domains=[domain])
        gold_plan = planner.plan(index, question,
                                 [{"domain": domain, "uri": expected[1]}],
                                 [{"domain": domain, "uri": expected[1]}],
                                 requested_domains=[domain])
        retrieved = expected in {(h.get("domain"), h.get("uri")) for h in hits}
        correct_selection = bool(selected and (domain, selected["uri"]) == expected)
        oracle_ready = gold_plan["status"] == "ready"
        rows.append({
            "question": question, "domain": domain,
            "gold_property": expected[1],
            "selected_property": selected["uri"] if selected else None,
            "gold_in_hybrid_top_k": retrieved,
            "top_ranked_in_domain_correct": correct_selection,
            "planner_status": plan["status"],
            "planner_reason": plan.get("reason"),
            "oracle_property_plan_ready": oracle_ready,
            "oracle_plan_reason": gold_plan.get("reason"),
            "exact_sparql_match_to_oracle": oracle_ready and plan.get("sparql") == gold_plan.get("sparql"),
            "generated_sparql": plan.get("sparql"),
        })
        if max_cases and len(rows) >= max_cases:
            break
    def count(key):
        return sum(bool(r[key]) for r in rows)
    n = len(rows)
    summary = {"evaluated": n, "skipped": len(skipped),
               "gold_property_retrieved_at_k": count("gold_in_hybrid_top_k"),
               "top_ranked_in_domain_correct": count("top_ranked_in_domain_correct"),
               "oracle_property_plan_ready": count("oracle_property_plan_ready"),
               "exact_sparql_match_to_oracle": count("exact_sparql_match_to_oracle"),
               "exact_sparql_match_rate": count("exact_sparql_match_to_oracle") / n if n else None}
    return {
        "evaluation_type": "single_domain_property_selection_oracle_scope",
        "benchmark_status": "provisional_review_required",
        "limitations": [
            "Domain scope is taken from provisional labels, not predicted from the question.",
            "Only cases with exactly one gold property are eligible for the v1 planner.",
            "Selection uses the highest-ranked retrieved property within the oracle domain.",
            "Oracle SPARQL is generated by the same planner; exact agreement is not independent semantic correctness.",
            "No instance data or SPARQL execution is evaluated.",
        ],
        "summary": summary, "cases": rows, "skipped": skipped,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--index", type=Path, default=DEFAULT_INDEX)
    parser.add_argument("--retrieval", type=Path, default=DEFAULT_RETRIEVAL)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--max-cases", type=int, default=15, help="0 evaluates all eligible cases")
    args = parser.parse_args()
    if args.max_cases < 0:
        parser.error("--max-cases must be nonnegative")
    index = json.loads(args.index.read_text(encoding="utf-8"))
    report = json.loads(args.retrieval.read_text(encoding="utf-8"))
    result = evaluate(index, report, load_planner(), args.max_cases)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps(result["summary"], indent=2))
    print("Wrote:", args.output)


if __name__ == "__main__":
    main()
